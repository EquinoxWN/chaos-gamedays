"""Render a plan as the Markdown pre-flight brief that is read out before the game day starts."""

from __future__ import annotations

from .model import Experiment


def _cell(text: str) -> str:
    """Escape text for a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def render(e: Experiment) -> str:
    """Markdown brief: hypothesis, steady state, fault, blast radius, abort conditions, rollback."""
    f, br = e.fault, e.blast_radius
    selector = ", ".join(f"{k}={v}" for k, v in sorted(f.selector.items()))
    params = ", ".join(f"{k}={v}" for k, v in sorted(f.parameters.items())) or "none"
    lines = [
        f"# {e.id}: {_cell(e.title)}",
        "",
        "_Generated by `gameday brief` from the sealed plan; do not edit by hand._",
        "",
        f"- **Service:** {e.service}",
        f"- **Owner:** {e.owner}",
        f"- **Scheduled start:** {e.scheduled_start:%Y-%m-%d %H:%M} UTC",
        f"- **Approved by:** {', '.join(e.approved_by)} at {e.approved_at:%Y-%m-%d %H:%M} UTC",
        "",
        "## Hypothesis",
        "",
        f"> {e.statement}",
        "",
        "Checked during the fault window, on every sample:",
        "",
        *[f"- `{x.text()}`" for x in e.expectations],
        "",
        "## Steady state (must hold before the fault starts)",
        "",
        "| Metric | Meaning | SLO |",
        "|---|---|---|",
        *[f"| `{s.metric}` | {_cell(s.description)} | `{s.slo.op} {s.slo.value:g} {s.unit}` |" for s in e.steady_state],
        "",
        "## Fault and load",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Fault | {f.kind} on `{selector}` in namespace `{f.namespace}` |",
        f"| Affected | {f.affected} of {f.replicas} pods |",
        f"| Duration | {f.duration_text} |",
        f"| Parameters | {params} |",
        f"| Load | k6, {e.load_rps} requests/s for {e.load_duration_text} |",
        "",
        "## Blast radius",
        "",
        "| Limit | Value |",
        "|---|---|",
        f"| Environment | {br.environment} |",
        f"| Namespaces | {', '.join(f'`{n}`' for n in br.namespaces)} |",
        f"| Max pods affected | {br.max_pods_affected} |",
        f"| Max traffic exposed | {br.max_traffic_pct}% |",
        f"| Max fault duration | {br.max_duration_text} |",
        f"| Dependencies in reach | {', '.join(br.dependencies) or 'none'} |",
        f"| Expected user impact | {_cell(br.user_impact)} |",
        "",
        "## Abort conditions (stop and roll back at once if any fires)",
        "",
        *[f"- `{a.bound.text()}` for {a.for_text}" for a in e.abort_conditions],
        "",
        "## Rollback",
        "",
        *[f"{i}. {step}" for i, step in enumerate(e.rollback, 1)],
        "",
    ]
    return "\n".join(lines)
